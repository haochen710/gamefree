/**
 * 宗门日常活动（需求 4）
 *
 * 需求原文：
 *   「宗门增加宗门建筑，除了掌门大殿和山门，其余建筑需钻研解锁，
 *     比如比武台、武技阁、功法殿、通天塔
 *     （弟子用建筑，弟子探索后增加心得，加快进境等，
 *      弟子使用这些建筑为随机事件，比武台除外，
 *      比武台由玩家决定是否开启，十年一次，
 *      每次大比结束全宗弟子修行速度增加，持续一年）」
 *
 * 拆成三件事：
 *   1. 心得（insight）—— 弟子探索后积累，直接加快自身修行；
 *   2. 随机事件     —— 弟子自发去武技阁 / 功法殿 / 通天塔，得到好处；
 *   3. 大比         —— 只有比武台例外：由玩家开关，每十年一次，
 *                      比完全宗弟子修行加速一年。
 */

/* ------------------------------------------------------------------ */
/* 心得（弟子探索后增加，加快进境）                                      */
/* ------------------------------------------------------------------ */

/** 每点心得提供的修行速度加成（0.01 = +1%） */
export const INSIGHT_SPEED_PER_POINT = 0.01;
/** 心得加速的上限（1.0 = 最多 +100%） */
export const INSIGHT_SPEED_CAP = 1;
/**
 * 心得上限。
 *
 * 刻意就定在「加速刚好满」的那一点（100 点 = +100%），
 * 而不是给一个更大的数 —— 否则界面上会看到"心得 878"这种
 * 早已不再产生任何效果的数字，玩家会以为它还在起作用。
 */
export const INSIGHT_MAX = INSIGHT_SPEED_CAP / INSIGHT_SPEED_PER_POINT;
/** 一次秘境探索，每名参与者获得的基础心得 */
export const INSIGHT_PER_EXPEDITION = 2;
/** 秘境越深，心得越多：每 1 级 minRealm 追加 */
export const INSIGHT_PER_REALM_LEVEL = 1;
/** 一次游历带回的心得（弟子不参与游历，所以这里是给"随行见闻"的量） */
export const INSIGHT_PER_TRAVEL = 1;

/* ------------------------------------------------------------------ */
/* 随机事件（弟子自发使用宗门建筑）                                      */
/* ------------------------------------------------------------------ */

/** 每隔多少秒判定一次随机事件 */
export const SECT_EVENT_INTERVAL = 45;
/** 每次判定的触发概率 */
export const SECT_EVENT_CHANCE = 0.5;

/** 功法殿事件：弟子顿悟，直接推进多少「年」的修为（占本境界的比例） */
export const EVENT_CULTIVATE_RATIO = 0.05;
/** 武技阁事件：获得多少心得 */
export const EVENT_MARTIAL_INSIGHT = 3;
/** 通天塔事件：获得多少心得（更高，因为塔本身稀有） */
export const EVENT_TOWER_INSIGHT = 5;
/** 通天塔事件额外提供的发现保底（相当于一次失败的探索） */
export const EVENT_TOWER_DISCOVERY_PITY = 0.05;

/* ------------------------------------------------------------------ */
/* 大比（比武台）                                                       */
/* ------------------------------------------------------------------ */

/** 多少游戏年举办一次大比 */
export const ARENA_INTERVAL_GAME_YEARS = 10;
/** 大比后的修行加速持续多少游戏年 */
export const ARENA_BUFF_GAME_YEARS = 1;
/** 大比带来的修行速度倍率（2 = 翻倍） */
export const ARENA_BUFF_MULTIPLIER = 2;
/** 大比结束后全宗弟子获得的心得 */
export const ARENA_INSIGHT_REWARD = 5;
/** 只有比武台这一座建筑能触发大比 */
export const ARENA_REQUIRED_BUILDING = 'arena';
